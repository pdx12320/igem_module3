def _cn(run, size=None, bold=None, color=None, italic=None):
    run.font.name = CN
    run._element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    if size is not None: run.font.size = Pt(size)
    if bold is not None: run.font.bold = bold
    if italic is not None: run.font.italic = italic
    if color is not None: run.font.color.rgb = RGBColor(*color)


def P(text="", size=10.5, bold=False, color=GRAY, align=None, after=6, before=0, indent=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.35
    if indent is not None: p.paragraph_format.left_indent = Cm(indent)
    if align == "c": p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); _cn(r, size, bold, color)
    return p


def RICH(segs, size=10.5, after=6, indent=None, align=None):
    """segs = [(text, bold, color), ...]"""
    p = doc.add_paragraph()
